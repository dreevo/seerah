package com.seerah.places.adapter.out.persistence;

import com.seerah.shared.ContentStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.JdbcType;
import org.hibernate.dialect.PostgreSQLEnumJdbcType;

import java.time.Instant;
import java.util.UUID;

/**
 * A place (§12.4). An essentially anaemic reference entity, so the module has no
 * {@code domain} package (§23.3). Latitude/longitude are stored directly; the
 * PostGIS {@code geom} column is generated by the database from them, so the JPA
 * layer needs no spatial types.
 */
@Entity
@Table(name = "place")
public class PlaceJpaEntity {

    @Id
    private UUID id;

    @Column(nullable = false, columnDefinition = "citext")
    private String slug;

    @Column(name = "place_type", nullable = false)
    private String placeType = "SETTLEMENT";

    private Double latitude;
    private Double longitude;

    @Column(name = "modern_name")
    private String modernName;

    @Column(name = "is_approximate", nullable = false)
    private boolean approximate;

    @Enumerated(EnumType.STRING)
    @JdbcType(PostgreSQLEnumJdbcType.class)
    @Column(nullable = false, columnDefinition = "content_status")
    private ContentStatus status = ContentStatus.PUBLISHED;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt = Instant.now();

    protected PlaceJpaEntity() { }

    public static PlaceJpaEntity create(String slug) {
        PlaceJpaEntity p = new PlaceJpaEntity();
        p.id = UUID.randomUUID();
        p.slug = slug;
        return p;
    }

    public UUID getId() { return id; }
    public String getSlug() { return slug; }
    public Double getLatitude() { return latitude; }
    public void setLatitude(Double v) { this.latitude = v; }
    public Double getLongitude() { return longitude; }
    public void setLongitude(Double v) { this.longitude = v; }
    public String getModernName() { return modernName; }
    public void setModernName(String v) { this.modernName = v; }
    public boolean isApproximate() { return approximate; }
    public void setApproximate(boolean v) { this.approximate = v; }
}
